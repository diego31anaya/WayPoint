"""Regenerate app/data/category_groups.py from the data layer's category rule.

Run from backend/: python -m scripts.gen_category_groups
"""
import csv
import gzip
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from data.categories import friendly_category  # noqa: E402

groups = {'cafe': set(), 'restaurant': set()}
with gzip.open(ROOT / 'data' / 'la_places.csv.gz', 'rt', encoding='utf-8') as f:
    for r in csv.DictReader(f):
        group = friendly_category(r['TOP_CATEGORY'], r['SUB_CATEGORY'], r['CATEGORY'])
        if group in groups and r['CATEGORY']:
            groups[group].add(r['CATEGORY'])

fmt = lambda s: '(\n' + ''.join(f'    {c!r},\n' for c in sorted(s)) + ')'
(Path(__file__).resolve().parents[1] / 'app' / 'data' / 'category_groups.py').write_text(f'''"""Overture categories in the data layer's "cafe" and "restaurant" groups (data/categories.py).

Generated by scripts/gen_category_groups.py so backend competitor counts match the frontend's numbers.
"""
CAFE = {fmt(groups['cafe'])}
RESTAURANT = {fmt(groups['restaurant'])}
''')
print({k: len(v) for k, v in groups.items()})
